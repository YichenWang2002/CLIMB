"""Render a compact, auditable report from revision evaluation JSON files.

The evaluator files are deliberately the source of truth.  This command does
not infer missing runs, select a checkpoint, or read held-out outcomes while
constructing a curriculum.  It only computes rates after generation has
finished, and it requires stable ``record_id`` values for paired comparisons.

Example::

    python -m experiments.revision.report_revision \
      --run flat=outputs/revision/.../flat_test.json \
      --run spcl=outputs/revision/.../spcl_test.json \
      --out outputs/revision/qwen_report.json

The same command is useful for the independent kitchen split; the subgroup
``new_primitive`` is detected from the ``+service`` scenario marker used by
the benchmark generator.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from .aggregate_revision import _details, _group, _paired

SUBGROUPS = ("overall", "T1", "T2", "T3", "coordination",
             "shared_primitive", "new_primitive")


def _parse_run(spec: str) -> tuple[str, Path]:
    if "=" not in spec:
        raise ValueError(f"--run must be label=path, got {spec!r}")
    label, raw_path = spec.split("=", 1)
    label = label.strip()
    path = Path(raw_path.strip())
    if not label or not raw_path.strip():
        raise ValueError(f"--run must be label=path, got {spec!r}")
    if not path.is_file():
        raise FileNotFoundError(path)
    return label, path


def _load(path: Path) -> dict:
    payload = json.loads(path.read_text(encoding="utf-8"))
    details = _details(payload)
    ids = [row.get("record_id") for row in details]
    if any(value is None for value in ids) or len(ids) != len(set(ids)):
        raise ValueError(f"{path} lacks unique record_id values")
    return payload


def _rates(payload: dict) -> dict[str, dict]:
    details = _details(payload)
    result = {}
    for subgroup in SUBGROUPS:
        selected = [row for row in details if _group(row, subgroup)]
        successes = sum(bool(row.get("success")) for row in selected)
        result[subgroup] = {
            "successes": successes,
            "n": len(selected),
            "rate": successes / max(1, len(selected)),
        }
    return result


def _latex(runs: dict[str, dict]) -> str:
    lines = ["% Generated by experiments.revision.report_revision.py",
             "\\begin{tabular}{lrrrrrrr}",
             "\\toprule",
             "run & overall & T1 & T2 & T3 & coord. & shared & new \\\\",
             "\\midrule"]
    for label, report in runs.items():
        rates = report["rates"]
        values = [100.0 * rates[key]["rate"] for key in SUBGROUPS]
        lines.append(label.replace("_", "\\_") + " & " +
                     " & ".join(f"{value:.1f}" for value in values) +
                     " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    return "\n".join(lines) + "\n"


def build(run_specs: list[str], pairs: list[str], bootstrap_samples: int,
          seed: int) -> dict:
    if not run_specs:
        raise ValueError("at least one --run label=path is required")
    loaded = {}
    for spec in run_specs:
        label, path = _parse_run(spec)
        if label in loaded:
            raise ValueError(f"duplicate run label {label!r}")
        loaded[label] = (path, _load(path))
    runs = {
        label: {"path": str(path), "n": len(_details(payload)),
                "rates": _rates(payload),
                "strict_success_rate": payload.get("strict_success_rate"),
                "overall": payload.get("overall")}
        for label, (path, payload) in loaded.items()
    }
    pair_specs = pairs
    if not pair_specs and {"flat", "spcl"}.issubset(loaded):
        pair_specs = ["flat,spcl"]
    paired = {}
    for spec in pair_specs:
        if "," not in spec:
            raise ValueError(f"--pair must be left,right, got {spec!r}")
        left, right = (part.strip() for part in spec.split(",", 1))
        if left not in loaded or right not in loaded:
            raise ValueError(f"unknown pair {spec!r}; available={sorted(loaded)}")
        left_payload, right_payload = loaded[left][1], loaded[right][1]
        paired[spec] = {
            subgroup: _paired(left_payload, right_payload,
                              bootstrap_samples, seed + i, subgroup)
            for i, subgroup in enumerate(SUBGROUPS)
        }
    return {"protocol_version": "iclr2027_revision_v1",
            "runs": runs, "paired": paired,
            "bootstrap_samples": bootstrap_samples, "seed": seed}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="append", required=True,
                        help="label=path to an evaluator JSON; repeatable")
    parser.add_argument("--pair", action="append", default=[],
                        help="left,right labels for paired exact/bootstrapped stats")
    parser.add_argument("--out", required=True)
    parser.add_argument("--bootstrap-samples", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    result = build(args.run, args.pair, args.bootstrap_samples, args.seed)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")
    csv_path = out.with_suffix(".csv")
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(("run", "subgroup", "successes", "n", "rate"))
        for label, report in result["runs"].items():
            for subgroup in SUBGROUPS:
                row = report["rates"][subgroup]
                writer.writerow((label, subgroup, row["successes"], row["n"], row["rate"]))
    tex_path = out.with_suffix(".tex")
    tex_path.write_text(_latex(result["runs"]), encoding="utf-8")
    print(json.dumps({"out": str(out), "csv": str(csv_path), "tex": str(tex_path),
                      "runs": sorted(result["runs"]),
                      "pairs": sorted(result["paired"])}, indent=2))


if __name__ == "__main__":
    main()
